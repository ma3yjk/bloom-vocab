-- BLOOM VOCAB: chạy toàn bộ file này trong Supabase SQL Editor.
-- Website cho phép mọi người xem công khai; thành viên đăng nhập mới được thêm từ; chỉ admin sửa/xóa và quản lý chủ đề.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('member','admin')),
  created_at timestamptz not null default now()
);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role) values (new.id, 'member')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_bloom on auth.users;
create trigger on_auth_user_created_bloom
after insert on auth.users
for each row execute procedure public.create_profile_for_new_user();

create or replace function public.is_bloom_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create table if not exists public.topics (
  id bigint generated by default as identity primary key,
  name text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.words (
  id uuid primary key default gen_random_uuid(),
  en text not null,
  vi text not null,
  topic text not null default 'Thông dụng',
  type text not null default '',
  example text not null default '',
  img text not null default '',
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);

create unique index if not exists words_en_lower_unique on public.words (lower(en));

alter table public.profiles enable row level security;
alter table public.topics enable row level security;
alter table public.words enable row level security;

drop policy if exists "profile read self or admin" on public.profiles;
create policy "profile read self or admin" on public.profiles
for select to authenticated
using (id = auth.uid() or public.is_bloom_admin());

-- Cấp quyền đọc công khai ở tầng SQL; RLS vẫn giới hạn mọi thao tác ghi.
grant select on public.topics, public.words to anon, authenticated;
grant insert on public.words to authenticated;
grant insert, update, delete on public.topics to authenticated;
grant update, delete on public.words to authenticated;

-- Không tạo policy UPDATE/INSERT cho profiles: thành viên không thể tự nâng quyền.

drop policy if exists "authenticated read topics" on public.topics;
drop policy if exists "public read topics" on public.topics;
create policy "public read topics" on public.topics
for select to anon, authenticated using (true);
drop policy if exists "admin insert topics" on public.topics;
create policy "admin insert topics" on public.topics
for insert to authenticated with check (public.is_bloom_admin());
drop policy if exists "admin update topics" on public.topics;
create policy "admin update topics" on public.topics
for update to authenticated using (public.is_bloom_admin()) with check (public.is_bloom_admin());
drop policy if exists "admin delete topics" on public.topics;
create policy "admin delete topics" on public.topics
for delete to authenticated using (public.is_bloom_admin());

drop policy if exists "authenticated read words" on public.words;
drop policy if exists "public read words" on public.words;
create policy "public read words" on public.words
for select to anon, authenticated using (true);
drop policy if exists "authenticated add words" on public.words;
create policy "authenticated add words" on public.words
for insert to authenticated with check (created_by = auth.uid());
drop policy if exists "admin update words" on public.words;
create policy "admin update words" on public.words
for update to authenticated using (public.is_bloom_admin()) with check (public.is_bloom_admin());
drop policy if exists "admin delete words" on public.words;
create policy "admin delete words" on public.words
for delete to authenticated using (public.is_bloom_admin());

insert into public.topics(name) values
